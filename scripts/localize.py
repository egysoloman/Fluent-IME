#!/usr/bin/env python3
"""Validate native .strings catalogs and generate typed Swift accessors.

Edit the zh-Hans/zh-Hant/en Localizable.strings files, then run this script. --check
is read-only and fails on drift, missing keys, duplicates, or unsafe formats.
"""
from pathlib import Path
import argparse, json, re, sys, plistlib
ROOT = Path(__file__).resolve().parent.parent
RESOURCES = ROOT / 'Sources/FluentIMECore/Resources'
LOCALES = ['zh-Hans', 'zh-Hant', 'en']
TARGET = ROOT / 'Sources/FluentIMECore/LocalizedStrings.swift'
TOKEN = re.compile(r'\s+|/\*.*?\*/|//[^\n]*|(?P<entry>"(?:[^"\\]|\\.)*"\s*=\s*"(?:[^"\\]|\\.)*"\s*;)', re.S)
STRINGS = re.compile(r'"(?:[^"\\]|\\.)*"')
FORMAT = re.compile(r'%(?P<index>[1-9]\d*)\$(?P<type>ld|@)')

def read_catalog(path):
    if path.read_bytes().startswith(b'bplist'):
        return plistlib.loads(path.read_bytes())
    text=path.read_text(); values={}; position=0
    while position<len(text):
        match=TOKEN.match(text,position)
        if not match: raise ValueError(f'{path}: invalid .strings syntax near {text[position:position+50]!r}')
        position=match.end()
        if match.group('entry'):
            key,value=map(json.loads,STRINGS.findall(match.group('entry')))
            if key in values: raise ValueError(f'{path}: duplicate key {key}')
            values[key]=value
    return values

def arguments(text):
    text=text.replace('%%',''); result={}
    for match in FORMAT.finditer(text):
        index=int(match['index']); kind=match['type']
        if index in result and result[index]!=kind: raise ValueError(f'Inconsistent argument types in {text}')
        result[index]=kind
    if '%' in FORMAT.sub('',text): raise ValueError(f'Use positional %@ / %ld arguments in {text}')
    if sorted(result)!=list(range(1,len(result)+1)): raise ValueError(f'Non-contiguous arguments in {text}')
    return result

def swift_name(key):
    parts=key.split('.'); return parts[0]+''.join(part[0].upper()+part[1:] for part in parts[1:])

def generate(catalog):
    lines=['// Generated by scripts/localize.py. Edit the .strings catalogs, then regenerate.', 'import Foundation', '', 'public extension L10n {']
    names=set()
    for key,value in sorted(catalog.items()):
        name=swift_name(key)
        if name in names or not re.fullmatch(r'[A-Za-z][A-Za-z0-9]*',name): raise ValueError(f'Invalid or colliding accessor: {key}')
        names.add(name); args=arguments(value)
        lines.append('    /// '+value)
        if args:
            params=', '.join(f'_ arg{i}: '+('String' if kind=='@' else 'Int') for i,kind in sorted(args.items()))
            values=', '.join('arg'+str(i) for i in sorted(args))
            lines.append(f'    static func {name}({params}) -> String {{ format("{key}", arguments: [{values}]) }}')
        else: lines.append(f'    static var {name}: String {{ text("{key}") }}')
    return '\n'.join(lines+['}', ''])

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    parser.add_argument('--bundle',type=Path,help='Also validate the assembled app resources')
    args=parser.parse_args()
    catalogs={locale:read_catalog(RESOURCES/f'{locale}.lproj/Localizable.strings') for locale in LOCALES}
    base=catalogs['zh-Hans']
    for locale,catalog in catalogs.items():
        if catalog.keys()!=base.keys(): raise ValueError(f'{locale}: missing {base.keys()-catalog.keys()}, extra {catalog.keys()-base.keys()}')
        for key,value in catalog.items():
            if not value.strip(): raise ValueError(f'{locale}: empty value for {key}')
            if arguments(value)!=arguments(base[key]): raise ValueError(f'{locale}: argument mismatch for {key}')
        info=read_catalog(ROOT/f'Resources/{locale}.lproj/InfoPlist.strings')
        if info['CFBundleDisplayName']!=catalog['app.name']: raise ValueError(f'{locale}: inconsistent app name')
    generated=generate(base)
    if args.check:
        if not TARGET.exists() or TARGET.read_text()!=generated: raise ValueError('Generated Swift accessors are stale; run scripts/localize.py')
    else: TARGET.write_text(generated)
    if args.bundle:
        resources=args.bundle/'Contents/Resources'
        module=resources/'FluentIME_FluentIMECore.bundle/Contents/Resources'
        for locale,catalog in catalogs.items():
            if read_catalog(module/f'{locale}.lproj/Localizable.strings')!=catalog:
                raise ValueError(f'Bundled {locale} strings differ from source')
            if read_catalog(resources/f'{locale}.lproj/InfoPlist.strings')!=read_catalog(ROOT/f'Resources/{locale}.lproj/InfoPlist.strings'):
                raise ValueError(f'Bundled {locale} application name differs from source')
    # Glyph artwork and conversion probes are content, not interface strings.
    for path in (ROOT/'Sources/FluentIME').glob('*.swift'):
        for number,line in enumerate(path.read_text().splitlines(),1):
            if line.lstrip().startswith('//'): continue
            if not re.search(r'"[^"\n]*[\u4e00-\u9fff][^"\n]*"',line): continue
            if path.name=='SettingsGlyph.swift' and '("字" as NSString)' in line: continue
            if path.name=='main.swift' and ('== "你好"' in line or 'dictionary deployed; nihao' in line): continue
            raise ValueError(f'{path.name}:{number}: interface text must use L10n')
    print(f'Localization validated: {len(base)} keys, {len(catalogs)} languages; formats and app names match.')
if __name__=='__main__':
    try: main()
    except ValueError as error: sys.exit(str(error))
