#!/usr/bin/env python3
"""Precompile spelling variants so toggles do not redeploy a live input method.

Rime's prism is a syllable index (tens of KB), shared by the four correction /
learning variants. Every independent fuzzy combination is ready before install.
Bit values match FuzzyPinyinRule.swift. Rules precede abbreviation so initials
also work for the derived spellings. Dictionary and learning database are shared.
"""
from pathlib import Path
import re
root = Path(__file__).resolve().parent.parent / 'Resources/Rime'
base = (root / 'fluent_pinyin.schema.yaml').read_text()
rules = [
    ('derive/^z([^h])/zh$1/', 'derive/^zh/z/'),
    ('derive/^c([^h])/ch$1/', 'derive/^ch/c/'),
    ('derive/^s([^h])/sh$1/', 'derive/^sh/s/'),
    ('derive/^n/l/', 'derive/^l/n/'),
    ('derive/^f/h/', 'derive/^h/f/'),
    ('derive/an$/ang/', 'derive/ang$/an/'),
    ('derive/en$/eng/', 'derive/eng$/en/'),
    ('derive/in$/ing/', 'derive/ing$/in/'),
]
ids = ['fluent_pinyin']
for mask in range(1 << len(rules)):
    suffix = f'_f{mask}' if mask else ''
    fuzzy = ''.join(f'    - {rule.replace("derive/", "fuzz/", 1)}\n' for bit, group in enumerate(rules) if mask & (1 << bit) for rule in group)
    for abbreviation in (0, 1):
        for correction in (0, 1):
            for learning in (0, 1):
                schema = f'fluent_pinyin_a{abbreviation}_c{correction}_l{learning}{suffix}'
                text = base.replace('schema_id: fluent_pinyin', f'schema_id: {schema}')
                text = text.replace('    - erase/^[mn]g?$/\n', '    - erase/^[mn]g?$/\n' + fuzzy)
                if not abbreviation:
                    text = '\n'.join(line for line in text.split('\n') if '- abbrev/' not in line)
                text = text.replace('  dictionary: fluent_pinyin', f'  dictionary: fluent_pinyin\n  prism: fluent_pinyin_a{abbreviation}{suffix}')
                text = text.replace('enable_user_dict: true', f'enable_user_dict: {str(bool(learning)).lower()}')
                if correction:
                    # A correction-enabled sentence search can discard the exact
                    # sentence before UI ranking. Keep an independent exact path.
                    block = re.search(r'^translator:\n(?:[ \t].*\n)*', text, re.M).group()
                    correction_block = block.replace('translator:', 'correction_translator:', 1).replace('enable_correction: false', 'enable_correction: true')
                    text += '\n' + correction_block + '  initial_quality: -1\n'
                    text = text.replace('translators: [punct_translator, script_translator]', 'translators: [punct_translator, script_translator, script_translator@correction_translator]')
                (root / f'{schema}.schema.yaml').write_text('# Generated by scripts/generate-schemas.py; edit the base schema.\n' + text)
                ids.append(schema)
                gram_schema = schema + '_g1'
                gram = text.replace(f'schema_id: {schema}', f'schema_id: {gram_schema}')
                gram = re.sub(r'^(translator|correction_translator):\n', r'\1:\n  contextual_suggestions: false\n  max_homophones: 8\n', gram, flags=re.M)
                gram += (root.parent / 'wanxiang-grammar.yaml').read_text()
                (root / f'{gram_schema}.schema.yaml').write_text('# Generated by scripts/generate-schemas.py; edit the base schema.\n' + gram)
                ids.append(gram_schema)
default = root / 'default.yaml'
text = re.sub(r'schema_list:\n(?:[ \t].*\n)*', 'schema_list:\n' + ''.join(f'  - schema: {schema}\n' for schema in ids), default.read_text())
text = re.sub(r"config_version: '[^']+'", "config_version: '1.8'", text)
default.write_text(text)
print(f'Generated {len(ids)} schemas, {2 * (1 << len(rules))} shared option prisms.')
