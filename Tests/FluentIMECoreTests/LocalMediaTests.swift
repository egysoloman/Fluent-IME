import XCTest
import AppKit
import ImageIO
import UniformTypeIdentifiers
@testable import FluentIMECore

final class LocalMediaTests: XCTestCase {
    private var pasteboard: NSPasteboard!
    override func setUp() { pasteboard = NSPasteboard(name: .init("FluentIME-Test-" + UUID().uuidString)) }
    override func tearDown() { pasteboard.releaseGlobally(); pasteboard = nil }
    private func copy(_ text: String, marker: String? = nil) {
        let item = NSPasteboardItem(); item.setString(text, forType: .string)
        if let marker { item.setString("1", forType: .init(marker)) }
        pasteboard.clearContents(); pasteboard.writeObjects([item])
    }
    func testClipboardNotificationsReachItsOwnPanelObserver() throws {
        let history = ClipboardHistory(pasteboard: pasteboard, automaticPolling: false, sensitiveInput: { false })
        var updates = 0
        let observer = NotificationCenter.default.addObserver(forName: ClipboardHistory.changed, object: history, queue: nil) { _ in updates += 1 }
        defer { NotificationCenter.default.removeObserver(observer) }
        history.setRecording(true)
        copy("panel sample"); history.poll()
        try history.clear(); history.setRecording(false)
        XCTAssertEqual(updates, 4, "The panel must refresh its recording state and entries")
    }
    func testClipboardOptInPauseAndClearNeverRecaptureExistingText() throws {
        copy("existing")
        let history = ClipboardHistory(pasteboard: pasteboard, automaticPolling: false, sensitiveInput: { false })
        history.poll(); XCTAssertTrue(history.entries.isEmpty)
        history.setRecording(true); history.poll(); XCTAssertTrue(history.entries.isEmpty)
        copy("new copy"); history.poll(); XCTAssertEqual(history.entries.map(\.text), ["new copy"])
        history.setRecording(false); copy("paused"); history.poll()
        XCTAssertEqual(history.entries.map(\.text), ["new copy"])
        history.setRecording(true); history.poll(); XCTAssertEqual(history.entries.count, 1)
        try history.clear(); history.poll(); XCTAssertTrue(history.entries.isEmpty)
        XCTAssertEqual(pasteboard.string(forType: .string), "paused", "Clear history leaves the system buffer alone")
    }
    func testClipboardSensitiveTypesAndSecureInputAreExcluded() {
        var secure = false
        let history = ClipboardHistory(pasteboard: pasteboard, automaticPolling: false, sensitiveInput: { secure })
        history.setRecording(true)
        for marker in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword", "com.apple.is-remote-clipboard", NSPasteboard.PasteboardType.fileURL.rawValue] {
            copy("sensitive test value", marker: marker); history.poll()
            XCTAssertTrue(history.entries.isEmpty, marker)
        }
        secure = true; copy("secure field"); history.poll()
        secure = false; history.poll(); XCTAssertTrue(history.entries.isEmpty)
        copy("public sample"); history.poll(); XCTAssertEqual(history.entries.count, 1)
        copy(String(repeating: "x", count: 64_001)); history.poll(); XCTAssertEqual(history.entries.count, 1)
    }
    func testClipboardBoundedDeduplicatedExpiringAndNotPersistent() throws {
        var clock = Date()
        let history = ClipboardHistory(pasteboard: pasteboard, automaticPolling: false, now: { clock }, sensitiveInput: { false })
        history.setRecording(true)
        for index in 0..<55 { copy("sample \(index)"); history.poll() }
        XCTAssertEqual(history.entries.count, 50)
        XCTAssertEqual(history.entries.first?.text, "sample 54")
        copy("sample 10"); history.poll()
        XCTAssertEqual(history.entries.first?.text, "sample 10"); XCTAssertEqual(history.entries.count, 50)
        try history.remove(history.entries[0].id); XCTAssertEqual(history.entries.count, 49)
        let second = ClipboardHistory(pasteboard: pasteboard, automaticPolling: false)
        XCTAssertTrue(second.entries.isEmpty); XCTAssertFalse(second.isRecording)
        history.setRecording(false); clock = clock.addingTimeInterval(1801); history.poll()
        XCTAssertTrue(history.entries.isEmpty)
    }
    func testGIFImportPersistenceCopyRemovalAndInvalidFile() throws {
        let scratch = FileManager.default.temporaryDirectory.appendingPathComponent("FluentIME-GIFTest-" + UUID().uuidString)
        try FileManager.default.createDirectory(at: scratch, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: scratch) }
        let source = scratch.appendingPathComponent("sample.gif")
        let context = try XCTUnwrap(CGContext(data: nil, width: 40, height: 40, bitsPerComponent: 8, bytesPerRow: 160, space: CGColorSpaceCreateDeviceRGB(), bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue))
        let destination = try XCTUnwrap(CGImageDestinationCreateWithURL(source as CFURL, UTType.gif.identifier as CFString, 2, nil))
        for color in [NSColor.systemBlue, NSColor.systemOrange] {
            context.setFillColor(color.cgColor); context.fill(CGRect(x: 0, y: 0, width: 40, height: 40))
            CGImageDestinationAddImage(destination, try XCTUnwrap(context.makeImage()), [kCGImagePropertyGIFDictionary: [kCGImagePropertyGIFDelayTime: 0.2]] as CFDictionary)
        }
        XCTAssertTrue(CGImageDestinationFinalize(destination))
        let directory = scratch.appendingPathComponent("library")
        let library = GIFLibrary(directory: directory)
        let entry = try library.add(source)
        XCTAssertEqual(try library.add(source), entry); XCTAssertEqual(library.entries.count, 1)
        XCTAssertEqual(GIFLibrary(directory: directory).entries, [entry])
        try library.copy(entry, to: pasteboard)
        XCTAssertEqual(pasteboard.data(forType: .init(UTType.gif.identifier)), try Data(contentsOf: source))
        XCTAssertEqual(CGImageSourceGetCount(try XCTUnwrap(CGImageSourceCreateWithURL(library.url(for: entry) as CFURL, nil))), 2)
        try library.remove(entry)
        XCTAssertTrue(library.entries.isEmpty); XCTAssertTrue(FileManager.default.fileExists(atPath: source.path))
        XCTAssertFalse(FileManager.default.fileExists(atPath: library.url(for: entry).path))
        let invalid = scratch.appendingPathComponent("invalid.gif")
        try Data("not a GIF".utf8).write(to: invalid)
        XCTAssertThrowsError(try library.add(invalid)); XCTAssertTrue(library.entries.isEmpty)
    }
}
